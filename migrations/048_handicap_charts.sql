-- Handicap chart markers (tee colours)
CREATE TABLE handicap_markers (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT '#FFFFFF',
  text_color TEXT NOT NULL DEFAULT '#1a1a1a',
  display_order INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Chart entries: one row per handicap index range per marker
CREATE TABLE handicap_chart_entries (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  marker_id INTEGER NOT NULL REFERENCES handicap_markers(id) ON DELETE CASCADE,
  row_order INTEGER NOT NULL,
  handicap_range TEXT NOT NULL,
  course_handicap TEXT NOT NULL,
  index_min REAL NOT NULL,
  index_max REAL NOT NULL
);

